const DICTIONARIES: Record<Language, Record<string, string>> = {
  "zh-CN": zhCN,
  en,
};

export type Dictionaries = Record<Language, Record<string, string>>;

export const DEFAULT_LANGUAGE: Language = "zh-CN";

/** Map anything locale-ish (`en-US`, `zh_CN`, `zh-Hans`) onto a supported language. */
export function normalizeLanguage(input: string | null | undefined): Language {
  if (!input) return DEFAULT_LANGUAGE;
  const value = input.trim().toLowerCase();
  if (value.startsWith("en")) return "en";
  if (value.startsWith("zh")) return "zh-CN";
  return DEFAULT_LANGUAGE;
}

let current: Language = DEFAULT_LANGUAGE;

export function setLanguage(input: string | null | undefined): Language {
  current = normalizeLanguage(input);
  return current;
}

export function getLanguage(): Language {
  return current;
}

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
}

/**
 * Resolve a key against a dictionary set. Lookup order: requested language ->
 * zh-CN -> the key itself. Missing keys deliberately surface as their key so
 * they are easy to spot.
 */
export function resolveKey(
  key: string,
  lang: Language = current,
  dictionaries: Dictionaries = DICTIONARIES,
): string {
  return dictionaries[lang][key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key;
}

/** Translate a key and interpolate `{name}` placeholders. */
export function t(key: string, vars?: Record<string, string | number>): string {
  return interpolate(resolveKey(key, current), vars);
}

export function hasTranslation(key: string, lang: Language = current): boolean {
  return Object.prototype.hasOwnProperty.call(DICTIONARIES[lang], key);
}

/** Exposed for tests: every key present in the Chinese source dictionary. */
export function dictionaryKeys(lang: Language = DEFAULT_LANGUAGE): string[] {
  return Object.keys(DICTIONARIES[lang]);
}
